const en: Dict = { ...enBase, ...EXTRA_EN };
const de: Dict = { ...deBase, ...EXTRA_DE };

export type MsgKey = keyof typeof fa;
export const DICTS: Record<Lang, Dict> = { fa, de, en };

export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function formatNumber(lang: Lang, n: number, digits = 0): string {
  return new Intl.NumberFormat(NUM_LOCALE[lang], { maximumFractionDigits: digits }).format(n);
}

export function detectInitialLang(stored: string | null): Lang {
  if (stored && (LANGS as string[]).includes(stored)) return stored as Lang;
  return 'fa';
}
